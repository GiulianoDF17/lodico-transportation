/* Photo pipeline — run with `npm run images`.
 * Takes every JPG/PNG/WebP in /assets/photos/, writes resized AVIF + WebP
 * versions to /public/img/, and records them in
 * src/content/photos.generated.js so the templates can use them.
 * Then reference a photo by its file name (without extension) in
 * src/content/business.js → photos. */

import { readdir, mkdir, writeFile } from 'node:fs/promises';
import { join, parse } from 'node:path';
import sharp from 'sharp';

const SRC = 'assets/photos';
const OUT = 'public/img';
const WIDTHS = [640, 1024, 1600];

await mkdir(OUT, { recursive: true });
const files = (await readdir(SRC)).filter((f) => /\.(jpe?g|png|webp)$/i.test(f));
const manifest = {};

for (const file of files) {
  const name = parse(file).name.toLowerCase().replace(/[^a-z0-9-]+/g, '-');
  const img = sharp(join(SRC, file)).rotate(); // respect phone orientation
  const meta = await img.metadata();
  const widths = WIDTHS.filter((w) => w <= meta.width);
  if (!widths.length) widths.push(meta.width);
  for (const w of widths) {
    const resized = img.clone().resize({ width: w, withoutEnlargement: true });
    await resized.clone().avif({ quality: 52 }).toFile(join(OUT, `${name}-${w}.avif`));
    await resized.clone().webp({ quality: 74 }).toFile(join(OUT, `${name}-${w}.webp`));
  }
  const ratio = meta.height / meta.width;
  const largest = widths[widths.length - 1];
  manifest[name] = { widths, width: largest, height: Math.round(largest * ratio) };
  console.log(`✓ ${file} → ${name} (${widths.join(', ')} px)`);
}

await writeFile(
  'src/content/photos.generated.js',
  `/* AUTO-GENERATED by \`npm run images\` — do not edit by hand.
 * Maps each photo name (file in /assets/photos without extension) to the
 * optimized sizes written to /public/img/. */
export default ${JSON.stringify(manifest, null, 2)};
`,
);
console.log(files.length ? `Done: ${files.length} photo(s).` : 'No photos found in assets/photos/.');
